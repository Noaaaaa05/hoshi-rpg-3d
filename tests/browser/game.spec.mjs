import { test, expect } from '@playwright/test';

test('renders, explores, saves and restores at a GitHub Pages subpath',async({page},testInfo)=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  page.on('console',e=>{if(e.type()==='error')errors.push(e.text());});
  await page.goto('/hoshi-rpg-3d/?debug=1');
  await expect(page.locator('#start-button')).toBeEnabled();
  await expect(page.locator('#error')).toBeHidden();
  await page.screenshot({path:testInfo.outputPath('title.png')});
  await page.locator('#start-button').click();
  await expect.poll(()=>page.evaluate(()=>window.__HOSHI_DEBUG__.started)).toBe(true);
  const start=await page.evaluate(()=>window.__HOSHI_DEBUG__.player);
  await page.keyboard.down('w');await page.waitForTimeout(1200);await page.keyboard.up('w');
  await expect.poll(()=>page.evaluate(()=>window.__HOSHI_DEBUG__.player.z)).toBeLessThan(start.z-2);
  await page.keyboard.down('Shift');await page.keyboard.down('w');await page.waitForTimeout(1100);await page.keyboard.up('w');await page.keyboard.up('Shift');
  await expect.poll(()=>page.evaluate(()=>window.__HOSHI_DEBUG__.stars.length)).toBeGreaterThan(0);
  await expect.poll(()=>page.evaluate(()=>window.__HOSHI_DEBUG__.player.stamina)).toBeLessThan(97);
  await page.locator('#jump-button').click();
  await expect.poll(()=>page.evaluate(()=>window.__HOSHI_DEBUG__.player.grounded),{intervals:[10,30,50]}).toBe(false);
  await expect.poll(()=>page.evaluate(()=>window.__HOSHI_DEBUG__.player.grounded)).toBe(true);
  const zone=await page.locator('#camera-zone').boundingBox();
  const before=await page.evaluate(()=>window.__HOSHI_DEBUG__.camera.yaw);
  await page.mouse.move(zone.x+zone.width*.35,zone.y+zone.height*.4);await page.mouse.down();
  await page.mouse.move(zone.x+zone.width*.35+110,zone.y+zone.height*.4+20,{steps:8});await page.mouse.up();
  await expect.poll(()=>page.evaluate(()=>window.__HOSHI_DEBUG__.camera.yaw)).toBeLessThan(before-.1);
  await page.locator('#pause-button').click();
  await expect(page.locator('#menu')).toBeVisible();
  const paused=await page.evaluate(()=>window.__HOSHI_DEBUG__.player.z);
  await page.keyboard.down('w');await page.waitForTimeout(250);await page.keyboard.up('w');
  expect(await page.evaluate(()=>window.__HOSHI_DEBUG__.player.z)).toBeCloseTo(paused,2);
  await page.locator('#quality').selectOption('low');
  await page.locator('#resume-button').click();
  await page.screenshot({path:testInfo.outputPath('exploration.png')});
  const progress=await page.evaluate(()=>({player:window.__HOSHI_DEBUG__.player,stars:window.__HOSHI_DEBUG__.stars}));
  await page.locator('#pause-button').click();await page.reload();await expect(page.locator('#start-button')).toBeEnabled();
  await expect(page.locator('#start-button')).toContainText('旅のつづきへ');await page.locator('#start-button').click();
  expect(await page.evaluate(()=>window.__HOSHI_DEBUG__.stars)).toEqual(progress.stars);
  expect((await page.evaluate(()=>window.__HOSHI_DEBUG__.player)).z).toBeCloseTo(progress.player.z,1);
  await page.locator('#pause-button').click();await page.locator('#home-button').click();
  expect((await page.evaluate(()=>window.__HOSHI_DEBUG__.player)).z).toBeCloseTo(12,1);
  expect(errors).toEqual([]);
  testInfo.annotations.push({type:'render metrics',description:JSON.stringify(await page.evaluate(()=>({drawCalls:window.__HOSHI_DEBUG__.drawCalls,triangles:window.__HOSHI_DEBUG__.triangles,pixelRatio:window.__HOSHI_DEBUG__.pixelRatio})))});
});

test('touch joystick, camera and dash work simultaneously and release cleanly',async({page,context},testInfo)=>{
  test.skip(testInfo.project.name!=='chromium-touch','Multi-touch CDP verification runs in the touch Chromium project.');
  await page.goto('/?debug=1');await expect(page.locator('#start-button')).toBeEnabled();await page.locator('#start-button').click();
  const client=await context.newCDPSession(page);
  const stick=await page.locator('#joystick').boundingBox(),zone=await page.locator('#camera-zone').boundingBox(),dash=await page.locator('#dash-button').boundingBox();
  const touches=[{x:stick.x+stick.width/2,y:stick.y+stick.height*.2,id:1},{x:zone.x+zone.width*.4,y:zone.y+50,id:2},{x:dash.x+dash.width/2,y:dash.y+dash.height/2,id:3}];
  const start=await page.evaluate(()=>window.__HOSHI_DEBUG__);
  await client.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:touches});
  touches[1].x+=80;await client.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:touches});
  await page.waitForTimeout(700);
  const active=await page.evaluate(()=>window.__HOSHI_DEBUG__);
  expect(active.player.dashing).toBe(true);expect(active.player.stamina).toBeLessThan(98);expect(active.player.z).toBeLessThan(start.player.z-1);
  expect(active.camera.yaw).toBeLessThan(start.camera.yaw-.1);
  expect(active.input.joyId).not.toBeNull();expect(active.input.cameraId).not.toBeNull();expect(active.input.dashId).not.toBeNull();
  await client.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await expect.poll(()=>page.evaluate(()=>window.__HOSHI_DEBUG__.input)).toEqual({joyId:null,cameraId:null,dashId:null});
  await expect.poll(()=>page.evaluate(()=>window.__HOSHI_DEBUG__.player.speed)).toBeLessThan(.1);
  await page.setViewportSize({width:390,height:844});await expect(page.locator('#rotate')).toBeVisible();
  await expect.poll(()=>page.evaluate(()=>window.__HOSHI_DEBUG__.paused)).toBe(true);
});
